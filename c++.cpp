#include <iostream>
using namespace std;

// calculate my age Application

int main() {
    cout << "=================\n";
    cout << "==calculate my age Application ==\n";
    cout << "=================\n";

    int age;
    cout << "Enter your age in years: ";
    cin >> age;
    int age_in_days = age * 365;
    int age_in_hours = age * 24 * 365; // Assuming 24 hours per day and 365 days per year
    int age_in_minutes = age * 60 * 24 * 365; // Assuming 60 minutes per hour, 24 hours per day, and 365 days per year
    cout << "Your age in days is: " << age_in_days << " days\n";
    cout << "Your age in hours is: " << age_in_hours << " hours\n";
    cout << "Your age in minutes is: " << age_in_minutes << " minutes\n";

    return 0;
}


